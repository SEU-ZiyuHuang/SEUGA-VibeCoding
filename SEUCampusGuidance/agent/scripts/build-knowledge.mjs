// 把 原校区指南-wiki/ 编译成 Agent 检索用的知识数据。
//
//   node scripts/build-knowledge.mjs
//
// 产出（均提交进仓库，线上不跑构建）：
//   data/knowledge.mjs          CAMPUSES + CHUNKS + ALIASES，ESM 具名导出
//   data/knowledge.report.json  构建报告，供人工 review
//   data/map-features.mjs       从 ../../data/map-features.js 转存，让 agent/ 自包含
//
// ── 和旧版的区别 ────────────────────────────────────────────
// 旧版直接吃 原校区指南-md文档整理/ 的六份长文档，得靠启发式切块：1800 字上限、
// 表格不能拆、再拿英文词根词典把「建议的知识分块」对齐到切出来的块上（7 个对不上）。
// 现在页面边界在 wiki 里是显式的——一个文件就是一个块——那一整套启发式全部删掉了。
//
// 改完 wiki 后必须先 node scripts/verify-wiki.mjs，再跑这个。

import fs from "node:fs/promises";
import path from "node:path";
import vm from "node:vm";
import { agentDir, repoDir, wikiDir, CAMPUS_TABLE } from "./guide-source.mjs";

const outputDir = path.join(agentDir, "data");

const report = {
  generatedAt: new Date().toISOString(),
  campuses: [],
  chunksWithoutPages: [],
  chunksWithoutSummary: [],
  danglingRelated: [],
  aliasCount: 0,
};

function parseFront(source, file) {
  const matched = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?/.exec(source);
  if (!matched) throw new Error(`${file}: 缺少 front-matter`);
  const meta = {};
  for (const line of matched[1].split(/\r?\n/)) {
    const at = line.indexOf(":");
    if (at < 0) continue;
    const key = line.slice(0, at).trim();
    const raw = line.slice(at + 1).trim();
    if (raw.startsWith("[") || raw.startsWith('"')) {
      try {
        meta[key] = JSON.parse(raw);
      } catch {
        throw new Error(`${file}: front-matter 字段 ${key} 不合法：${raw.slice(0, 60)}`);
      }
    } else {
      meta[key] = raw;
    }
  }
  return [meta, source.slice(matched[0].length).trim()];
}

/** _campus.md 里的 ## 小节 → { 标题: 正文 }。notice / answerRules 要注入 system prompt。 */
function parseCampusHome(body) {
  const sections = {};
  let current = null;
  for (const line of body.split(/\r?\n/)) {
    const heading = /^##\s+(.+)$/.exec(line);
    if (heading) {
      current = heading[1].trim();
      sections[current] = [];
      continue;
    }
    if (current) sections[current].push(line);
  }
  return Object.fromEntries(
    Object.entries(sections).map(([title, lines]) => [title, lines.join("\n").trim()]));
}

async function readCampus(slug) {
  const dir = path.join(wikiDir, slug);
  const names = (await fs.readdir(dir)).filter((name) => name.endsWith(".md")).sort();

  const homeRaw = await fs.readFile(path.join(dir, "_campus.md"), "utf8");
  const [homeMeta, homeBody] = parseFront(homeRaw, `${slug}/_campus.md`);
  const home = parseCampusHome(homeBody);

  const chunks = [];
  for (const name of names) {
    if (name === "_campus.md") continue;
    const file = `${slug}/${name}`;
    const [meta, body] = parseFront(await fs.readFile(path.join(dir, name), "utf8"), file);
    if (!body) throw new Error(`${file}: 正文为空`);
    chunks.push({
      id: meta.id,
      campus: slug,
      campusName: homeMeta.name,
      version: homeMeta.version,
      sectionPath: meta.title,
      chunkKey: meta.chunk_key || "",
      summary: meta.summary || "",
      keywords: meta.keywords || [],
      aliasPairs: meta.alias_pairs || [],
      related: meta.related || [],
      pages: meta.pages || [],
      text: body,
    });
  }

  return {
    campus: {
      slug,
      name: homeMeta.name,
      aliases: homeMeta.aliases || [],
      version: homeMeta.version,
      notice: home["时效提醒"] || "",
      answerRules: home["回答规则"] || "",
    },
    chunks,
  };
}

/** map-features.js 是给浏览器写的 window 全局脚本，用 vm 加个假 window 把它读出来。 */
async function buildMapFeatures() {
  const source = await fs.readFile(path.join(repoDir, "data", "map-features.js"), "utf8");
  const sandbox = { window: {} };
  vm.createContext(sandbox);
  vm.runInContext(source, sandbox);
  const features = sandbox.window.MAP_FEATURES || [];
  await fs.writeFile(
    path.join(outputDir, "map-features.mjs"),
    `// AUTO-GENERATED by scripts/build-knowledge.mjs —— 请勿手工编辑\n\nexport const MAP_FEATURES = ${JSON.stringify(features, null, 2)};\n`,
    "utf8");
  return features.length;
}

const campuses = [];
const chunks = [];

for (const entry of CAMPUS_TABLE) {
  const { campus, chunks: campusChunks } = await readCampus(entry.slug);
  campuses.push(campus);
  chunks.push(...campusChunks);
  report.campuses.push({
    slug: entry.slug,
    chunks: campusChunks.length,
    chunkChars: campusChunks.reduce((n, chunk) => n + chunk.text.length, 0),
    withAliases: campusChunks.filter((chunk) => chunk.aliasPairs.length).length,
  });
}

// 质量检查，写进报告供人工 review diff
const ids = new Set(chunks.map((chunk) => chunk.id));
for (const chunk of chunks) {
  if (!chunk.pages.length) report.chunksWithoutPages.push(chunk.id);
  if (!chunk.summary) report.chunksWithoutSummary.push(chunk.id);
  for (const target of chunk.related) {
    if (!ids.has(target)) report.danglingRelated.push(`${chunk.id} → ${target}`);
  }
}

// 别名表 = 人工种子表（权威）+ 各页 alias_pairs（模型生成）。
// 种子表是团队实测的既定结论，不允许被模型条目覆盖：2026-08 那次重跑就漏掉了
// 「剪头发→理发」这个原本硬编码在 tools.mjs 里的核心用例。
const seedPath = path.join(wikiDir, "aliases.seed.json");
const seedRaw = JSON.parse(await fs.readFile(seedPath, "utf8"));
const seed = Object.fromEntries(Object.entries(seedRaw).filter(([key]) => !key.startsWith("_")));

const aliasesRaw = Object.fromEntries(Object.entries(seed).map(([k, v]) => [k, [...v]]));
const seeded = new Set(Object.keys(aliasesRaw));
let aliasDropped = 0;
for (const chunk of chunks) {
  for (const pair of chunk.aliasPairs || []) {
    const spoken = String(pair.spoken || "").trim();
    const written = String(pair.written || "").trim();
    // written 必须真的出现在该页正文里，否则扩展出来的词在知识库里匹配不到
    if (spoken.length < 2 || written.length < 2 || spoken === written || !chunk.text.includes(written)) {
      aliasDropped += 1;
      continue;
    }
    if (seeded.has(spoken)) continue;
    aliasesRaw[spoken] = [...new Set([...(aliasesRaw[spoken] || []), written])].slice(0, 6);
  }
}
for (const chunk of chunks) delete chunk.aliasPairs; // 运行时用不到，别进产物
const aliases = Object.fromEntries(Object.entries(aliasesRaw).sort(([a], [b]) => a.localeCompare(b, "zh")));
report.aliasCount = Object.keys(aliases).length;
report.aliasSeeded = seeded.size;
report.aliasDropped = aliasDropped;

const build = {
  generatedAt: report.generatedAt,
  campusCount: campuses.length,
  chunkCount: chunks.length,
  chunkChars: chunks.reduce((n, chunk) => n + chunk.text.length, 0),
  aliasCount: report.aliasCount,
};
report.build = build;
report.mapFeatures = await buildMapFeatures();

await fs.writeFile(path.join(outputDir, "knowledge.mjs"), [
  "// AUTO-GENERATED by scripts/build-knowledge.mjs —— 请勿手工编辑",
  "// 数据源：原校区指南-wiki/（一个 .md 文件 = 一个 chunk）",
  "",
  `export const KNOWLEDGE_BUILD = ${JSON.stringify(build, null, 2)};`,
  "",
  `export const CAMPUSES = ${JSON.stringify(campuses, null, 2)};`,
  "",
  "// 口语词 → 指南用词。检索期做查询扩展，治「剪头发」查不到「理发」。",
  `export const ALIASES = ${JSON.stringify(aliases, null, 2)};`,
  "",
  `export const CHUNKS = ${JSON.stringify(chunks, null, 2)};`,
  "",
].join("\n"), "utf8");

await fs.writeFile(path.join(outputDir, "knowledge.report.json"), `${JSON.stringify(report, null, 2)}\n`, "utf8");

console.log(`${build.campusCount} 个校区 / ${build.chunkCount} 个块 / ${build.chunkChars} 字 / 别名 ${build.aliasCount} 条（种子 ${report.aliasSeeded}，丢弃 ${report.aliasDropped}）`);
for (const item of report.campuses) {
  console.log(`  ${item.slug.padEnd(12)} ${String(item.chunks).padStart(2)} 块 ${String(item.chunkChars).padStart(6)} 字  带别名 ${item.withAliases}/${item.chunks}`);
}
if (report.chunksWithoutPages.length) console.log(`⚠ 无源图页码：${report.chunksWithoutPages.join("、")}`);
if (report.chunksWithoutSummary.length) console.log(`⚠ 无摘要：${report.chunksWithoutSummary.join("、")}`);
if (report.danglingRelated.length) console.log(`⚠ related 断链：${report.danglingRelated.join("、")}`);
console.log(`map-features ${report.mapFeatures} 条`);
